"""Sinh / cập nhật code Remotion từ timeline.json.

  python scaffold_remotion.py productions/<slug> [--no-captions]

Cần project Remotion ở productions/<slug>/project (create-video --blank) đã cài @remotion/media.
- src/pipeline/data.ts, src/pipeline/Pipeline.tsx: sinh lại mỗi lần chạy.
- src/pipeline/Captions.tsx: sinh lại nếu còn dấu GENERATED.
- src/scenes/<Sxx>.tsx: chỉ tạo khi chưa có (nơi thiết kế từng cảnh).
- src/Root.tsx: thay bản blank mặc định bằng bản đăng ký composition "Main"; nếu đã sửa thì in đoạn cần thêm.
- Sao chép audio/, images/, video/, fonts/ vào public/.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

MARK = "// GENERATED by scaffold_remotion.py: sửa script.json/assets.json rồi chạy lại; xoá dòng này nếu muốn sửa tay"


def comp_name(sid):
    return sid[:1].upper() + sid[1:]


def write_generated(path, content):
    if path.exists() and MARK not in path.read_text(encoding="utf-8"):
        print(f"skip {path.name}: đã sửa tay (không còn dấu GENERATED)")
        return
    path.write_text(content, encoding="utf-8")


SCENE_STUB = """import {{AbsoluteFill, interpolate, spring, useCurrentFrame, useVideoConfig}} from 'remotion';
import type {{SceneProps}} from '../pipeline/Pipeline';

// TODO thiết kế cảnh: {visual}
export const {name}: React.FC<SceneProps> = ({{words}}) => {{
\tconst frame = useCurrentFrame();
\tconst {{fps, width, height}} = useVideoConfig();
\tconst enter = spring({{frame: frame - 3, fps, config: {{damping: 200}}}});
\treturn (
\t\t<AbsoluteFill style={{{{backgroundColor: '{bg}', color: '{ink}', justifyContent: 'center', alignItems: 'center'}}}}>
\t\t\t<h1
\t\t\t\tstyle={{{{
\t\t\t\t\tfontFamily: "'{font}', sans-serif",
\t\t\t\t\tfontSize: Math.round(Math.min(width, height) * 0.09),
\t\t\t\t\tfontWeight: 800,
\t\t\t\t\ttextAlign: 'center',
\t\t\t\t\tmaxWidth: '80%',
\t\t\t\t\topacity: enter,
\t\t\t\t\ttransform: `translateY(${{interpolate(enter, [0, 1], [40, 0])}}px)`,
\t\t\t\t}}}}
\t\t\t>
\t\t\t\t{title}
\t\t\t</h1>
\t\t</AbsoluteFill>
\t);
}};
"""

CAPTIONS = MARK + """
import {AbsoluteFill, interpolate, useCurrentFrame, useVideoConfig} from 'remotion';
import type {Caption} from './data';

export const Captions: React.FC<{captions: readonly Caption[]; font: string}> = ({captions, font}) => {
\tconst frame = useCurrentFrame();
\tconst {fps, width, height} = useVideoConfig();
\tconst t = frame / fps;
\tconst current = captions.find((c, i) => t >= c.start - 0.05 && t < Math.min(c.end + 0.15, captions[i + 1]?.start ?? Infinity));
\tif (!current) {
\t\treturn null;
\t}
\tconst appear = interpolate(t, [current.start - 0.05, current.start + 0.07], [0, 1], {extrapolateLeft: 'clamp', extrapolateRight: 'clamp'});
\tconst portrait = height > width;
\treturn (
\t\t<AbsoluteFill style={{justifyContent: 'flex-end', alignItems: 'center', paddingBottom: portrait ? 640 : 110}}>
\t\t\t<span
\t\t\t\tstyle={{
\t\t\t\t\tmaxWidth: width * 0.8,
\t\t\t\t\tpadding: '10px 22px',
\t\t\t\t\tborderRadius: 14,
\t\t\t\t\tbackground: 'rgba(0,0,0,0.55)',
\t\t\t\t\tcolor: '#fff',
\t\t\t\t\tfontFamily: `'${font}', sans-serif`,
\t\t\t\t\tfontWeight: 700,
\t\t\t\t\tfontSize: portrait ? 64 : 58,
\t\t\t\t\tlineHeight: 1.2,
\t\t\t\t\ttextAlign: 'center',
\t\t\t\t\topacity: appear,
\t\t\t\t\ttransform: `translateY(${(1 - appear) * 12}px)`,
\t\t\t\t}}
\t\t\t>
\t\t\t\t{current.text}
\t\t\t</span>
\t\t</AbsoluteFill>
\t);
};
"""

ROOT = MARK + """
import {PipelineComposition} from './pipeline/Pipeline';

export const RemotionRoot: React.FC = () => {
\treturn (
\t\t<>
\t\t\t<PipelineComposition />
\t\t</>
\t);
};
"""


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser()
    p.add_argument("production")
    p.add_argument("--no-captions", action="store_true")
    args = p.parse_args()

    base = Path(args.production)
    proj = base / "project"
    if not (proj / "package.json").exists():
        sys.exit(f"Chưa có project Remotion ở {proj}. Chạy: npx create-video@latest --yes --blank --no-tailwind {proj}")
    tl = json.loads((base / "timeline.json").read_text(encoding="utf-8"))
    script = json.loads((base / "script.json").read_text(encoding="utf-8"))
    assets_file = base / "assets.json"
    assets = json.loads(assets_file.read_text(encoding="utf-8")) if assets_file.exists() else {}
    style = script.get("style", {})
    palette = style.get("palette") or ["#0B1020", "#F5F7FF"]
    font = style.get("font") or "Inter"
    fps = tl["fps"]
    by_id = {s["id"]: s for s in script["scenes"]}

    for sub in ["audio", "images", "video", "fonts"]:
        if (base / sub).exists():
            shutil.copytree(base / sub, proj / "public" / sub, dirs_exist_ok=True,
                            ignore=shutil.ignore_patterns(".tts-cache.json", "*.words.json"))

    src = proj / "src"
    (src / "pipeline").mkdir(parents=True, exist_ok=True)
    (src / "scenes").mkdir(parents=True, exist_ok=True)

    data = {"fps": fps, "width": tl["width"], "height": tl["height"], "totalFrames": tl["total_frames"],
            "captions": tl["captions"] if not args.no_captions else []}
    data_json = json.dumps(data, ensure_ascii=False, indent="\t")
    (src / "pipeline" / "data.ts").write_text(
        f"{MARK}\nexport type Caption = {{text: string; start: number; end: number}};\n"
        f"export const timeline = {data_json} as const;\n", encoding="utf-8")

    imports, seqs = [], []
    for s in tl["scenes"]:
        sid, name = s["id"], comp_name(s["id"])
        stub = src / "scenes" / f"{name}.tsx"
        if not stub.exists():
            sc = by_id.get(sid, {})
            title = json.dumps(sc.get("onscreen") or sid, ensure_ascii=False)
            stub.write_text(SCENE_STUB.format(name=name, visual=sc.get("visual", "").replace("\n", " "),
                                              bg=palette[0], ink=palette[1 % len(palette)], font=font,
                                              title="{" + title + "}"), encoding="utf-8")
            print(f"new  src/scenes/{name}.tsx")
        imports.append(f"import {{{name}}} from '../scenes/{name}';")
        # Mốc từ tính lại theo giây trong cảnh.
        words = [{"text": w["text"], "start": round(w["start"] - s["start"], 3), "end": round(w["end"] - s["start"], 3)}
                 for w in s["words"]]
        voice = ""
        if s.get("voice"):
            voice = (f"\n\t\t\t\t<Sequence name=\"voice-{sid}\" from={{{round(s['voice_offset'] * fps)}}} layout=\"none\">"
                     f"\n\t\t\t\t\t<Audio src={{staticFile('{s['voice']}')}} />\n\t\t\t\t</Sequence>")
        seqs.append(f"\t\t\t<Sequence name=\"{sid}\" from={{{s['start_frame']}}} durationInFrames={{{s['duration_frames']}}}>"
                    f"\n\t\t\t\t<{name} words={{{json.dumps(words, ensure_ascii=False)}}} />{voice}\n\t\t\t</Sequence>")
    starts = {s["id"]: s["start_frame"] for s in tl["scenes"]}
    for j, fx in enumerate(assets.get("sfx", [])):
        frm = starts.get(fx.get("scene"), 0) + round(float(fx.get("at", 0)) * fps)
        seqs.append(f"\t\t\t<Sequence name=\"sfx-{j:02}\" from={{{frm}}} layout=\"none\">"
                    f"\n\t\t\t\t<Audio src={{staticFile('{fx['path']}')}} volume={{{fx.get('volume', 0.6)}}} />\n\t\t\t</Sequence>")
    if assets.get("bgm"):
        bgm = assets["bgm"]
        seqs.append(f"\t\t\t<Audio src={{staticFile('{bgm['path']}')}} volume={{{bgm.get('volume', 0.14)}}} loop />")
    if not args.no_captions:
        seqs.append(f"\t\t\t<Captions captions={{timeline.captions}} font=\"{font}\" />")

    pipeline = f"""{MARK}
import {{Audio}} from '@remotion/media';
import {{AbsoluteFill, Composition, Sequence, staticFile}} from 'remotion';
import {{Captions}} from './Captions';
import {{timeline}} from './data';
{chr(10).join(imports)}

export type Word = {{text: string; start: number; end: number}};
export type SceneProps = {{words: readonly Word[]}};

export const PipelineVideo: React.FC = () => {{
\treturn (
\t\t<AbsoluteFill style={{{{backgroundColor: '{palette[0]}'}}}}>
{chr(10).join(seqs)}
\t\t</AbsoluteFill>
\t);
}};

export const PipelineComposition: React.FC = () => {{
\treturn (
\t\t<Composition
\t\t\tid="Main"
\t\t\tcomponent={{PipelineVideo}}
\t\t\tdurationInFrames={{{tl['total_frames']}}}
\t\t\tfps={{{fps}}}
\t\t\twidth={{{tl['width']}}}
\t\t\theight={{{tl['height']}}}
\t\t/>
\t);
}};
"""
    (src / "pipeline" / "Pipeline.tsx").write_text(pipeline, encoding="utf-8")
    write_generated(src / "pipeline" / "Captions.tsx", CAPTIONS)

    root = src / "Root.tsx"
    current = root.read_text(encoding="utf-8") if root.exists() else ""
    if "PipelineComposition" in current:
        pass
    elif not current or MARK in current or "from \"./Composition\"" in current or "from './Composition'" in current:
        root.write_text(ROOT, encoding="utf-8")
        print("wrote src/Root.tsx (composition id: Main)")
    else:
        print("Root.tsx đã sửa tay: thêm `import {PipelineComposition} from './pipeline/Pipeline';` và `<PipelineComposition />`")
    print(f"wrote src/pipeline ({len(tl['scenes'])} scenes, {tl['total_frames']} frames @ {fps}fps, {tl['width']}x{tl['height']})")


if __name__ == "__main__":
    main()
