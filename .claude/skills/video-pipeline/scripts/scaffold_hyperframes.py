"""Sinh / cập nhật project HyperFrames từ timeline.json.

  python scaffold_hyperframes.py productions/<slug> [--no-captions]

- project/index.html và project/compositions/captions.html: sinh lại mỗi lần chạy (có dấu GENERATED).
  Nếu đã xoá dấu GENERATED (sửa tay) thì bỏ qua file đó và in ra thời điểm cần cập nhật.
- project/compositions/<scene>.html: chỉ tạo khi chưa có (đây là nơi thiết kế từng cảnh).
- Sao chép audio/, images/, video/, fonts/ của production vào project/assets/.
"""
import argparse
import html
import json
import shutil
import io
import sys
import tarfile
import urllib.request
from pathlib import Path

MARK = "<!-- GENERATED by scaffold_hyperframes.py: sửa script.json/assets.json rồi chạy lại; xoá dòng này nếu muốn sửa tay -->"
GSAP_VERSION = "3.14.2"
GSAP = "assets/vendor/gsap.min.js"


def vendor_gsap(proj):
    """Đóng gói GSAP vào project, lấy từ npm registry (cloud session chặn jsdelivr, render không cần mạng)."""
    dest = proj / GSAP
    if dest.exists():
        return
    cache = Path.home() / ".cache" / "gen-video" / f"gsap-{GSAP_VERSION}.min.js"
    if not cache.exists():
        url = f"https://registry.npmjs.org/gsap/-/gsap-{GSAP_VERSION}.tgz"
        with urllib.request.urlopen(url, timeout=60) as resp:
            tar = tarfile.open(fileobj=io.BytesIO(resp.read()), mode="r:gz")
        data = tar.extractfile("package/dist/gsap.min.js").read()
        cache.parent.mkdir(parents=True, exist_ok=True)
        cache.write_bytes(data)
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(cache, dest)
    print(f"vendor {GSAP} (gsap {GSAP_VERSION})")


def esc(s):
    return html.escape(str(s), quote=True)


def write_generated(path, content):
    if path.exists() and MARK not in path.read_text(encoding="utf-8"):
        print(f"skip {path.name}: đã sửa tay (không còn dấu GENERATED) — cập nhật thời điểm bằng tay hoặc `npx hyperframes timeline`")
        return False
    path.write_text(content, encoding="utf-8")
    return True


def font_faces(assets):
    out = []
    for f in assets.get("fonts", []):
        src = "assets/" + f["path"]
        out.append(f"@font-face {{ font-family: '{f['family']}'; src: url('{src}'); "
                   f"font-weight: {f.get('weight', 'normal')}; font-display: block; }}")
    return "\n      ".join(out)


def scene_stub(sc, tl_scene, script_scene, w, h, style, first=False):
    sid = sc["id"]
    # Khung 0 là thumbnail trên mạng xã hội: cảnh đầu không được bắt đầu từ màn hình trống.
    enter = ('{{ scale: 0.94 }}, {{ scale: 1, duration: 0.6, ease: "power3.out" }}, 0' if first else
             '{{ opacity: 0, y: 40 }}, {{ opacity: 1, y: 0, duration: 0.5, ease: "power3.out" }}, 0.1')
    title = script_scene.get("onscreen") or sid
    dur = tl_scene["duration"]
    palette = style.get("palette") or ["#0B1020", "#F5F7FF", "#FF5A36"]
    font = style.get("font") or "Inter"
    visual = script_scene.get("visual", "")
    return f"""<template>
  <style>
    #root {{ position: absolute; inset: 0; background: {palette[0]}; color: {palette[1 % len(palette)]};
      font-family: '{font}', Inter, sans-serif; display: flex; align-items: center; justify-content: center; }}
    #{sid}-title {{ font-size: {int(min(w, h) * 0.09)}px; font-weight: 800; letter-spacing: -0.02em;
      text-align: center; max-width: 80%; line-height: 1.1; }}
  </style>
  <div id="root" data-composition-id="{sid}" data-width="{w}" data-height="{h}">
    <!-- TODO thiết kế cảnh: {esc(visual)} -->
    <h1 id="{sid}-title" class="clip" data-start="0" data-duration="{dur}" data-var-text="{sid}-title">{esc(title)}</h1>
  </div>
  <script>
    const tl = gsap.timeline({{ paused: true }});
    tl.fromTo("#{sid}-title", {enter.format()});
    window.__timelines["{sid}"] = tl;
  </script>
</template>
"""


def captions_comp(timeline, w, h, style):
    portrait = h > w
    bottom = 640 if portrait else 110
    size = 64 if portrait else 58
    font = style.get("font") or "Inter"
    groups, tweens = [], []
    for i, c in enumerate(timeline["captions"]):
        cid = f"cap-{i:04}"
        start = max(c["start"] - 0.05, 0.1 if i == 0 else 0)
        end = c["end"] + 0.15
        if i + 1 < len(timeline["captions"]):
            end = min(end, timeline["captions"][i + 1]["start"] - 0.05)  # = start của cụm sau: không chồng nhau
        dur = round(max(end - start, 0.2), 3)
        groups.append(f'    <div id="{cid}" class="clip cap" data-start="{start:.3f}" data-duration="{dur}">'
                      f'<span>{esc(c["text"])}</span></div>')
        tweens.append(f'    tl.fromTo("#{cid} span", {{ opacity: 0, y: 12 }}, '
                      f'{{ opacity: 1, y: 0, duration: 0.12, ease: "power2.out" }}, {start:.3f});')
    return f"""{MARK}
<template>
  <style>
    #root {{ position: absolute; inset: 0; pointer-events: none; }}
    .cap {{ position: absolute; left: 0; right: 0; bottom: {bottom}px; text-align: center; overflow: visible; }}
    .cap span {{ display: inline-block; max-width: {int(w * 0.8)}px; padding: 10px 22px; border-radius: 14px;
      background: rgba(0,0,0,0.55); color: #fff; font-family: '{font}', Inter, sans-serif; font-weight: 700;
      font-size: {size}px; line-height: 1.2; }}
  </style>
  <div id="root" data-composition-id="captions" data-width="{w}" data-height="{h}">
{chr(10).join(groups)}
  </div>
  <script>
    const tl = gsap.timeline({{ paused: true }});
{chr(10).join(tweens)}
    window.__timelines["captions"] = tl;
  </script>
</template>
"""


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser()
    p.add_argument("production")
    p.add_argument("--no-captions", action="store_true")
    args = p.parse_args()

    base = Path(args.production)
    tl = json.loads((base / "timeline.json").read_text(encoding="utf-8"))
    script = json.loads((base / "script.json").read_text(encoding="utf-8"))
    assets_file = base / "assets.json"
    assets = json.loads(assets_file.read_text(encoding="utf-8")) if assets_file.exists() else {}
    style = script.get("style", {})
    w, h, total = tl["width"], tl["height"], tl["total_duration"]
    by_id = {s["id"]: s for s in script["scenes"]}

    proj = base / "project"
    vendor_gsap(proj)
    (proj / "compositions").mkdir(parents=True, exist_ok=True)
    for sub in ["audio", "images", "video", "fonts"]:
        if (base / sub).exists():
            shutil.copytree(base / sub, proj / "assets" / sub, dirs_exist_ok=True,
                            ignore=shutil.ignore_patterns(".tts-cache.json", "*.words.json"))

    hosts, audios = [], []
    for i, s in enumerate(tl["scenes"]):
        sid = s["id"]
        hosts.append(f'      <div id="{sid}" data-composition-id="{sid}" data-composition-src="compositions/{sid}.html" '
                     f'data-start="{s["start"]}" data-duration="{s["duration"]}" data-track-index="1" '
                     f'data-track-kind="graphics" data-width="{w}" data-height="{h}"></div>')
        stub = proj / "compositions" / f"{sid}.html"
        if not stub.exists():
            stub.write_text(scene_stub(s, s, by_id.get(sid, {}), w, h, style, first=i == 0), encoding="utf-8")
            print(f"new  compositions/{sid}.html")
        if s.get("voice"):
            audios.append(f'      <audio id="vo-{sid}" src="assets/{s["voice"]}" data-start="{round(s["start"] + s["voice_offset"], 3)}" '
                          f'data-duration="{s["voice_duration"]}" data-track-index="10"></audio>')
    starts = {s["id"]: s["start"] for s in tl["scenes"]}
    for j, fx in enumerate(assets.get("sfx", [])):
        at = round(starts.get(fx.get("scene"), 0) + float(fx.get("at", 0)), 3)
        audios.append(f'      <audio id="sfx-{j:02}" src="assets/{fx["path"]}" data-start="{at}" '
                      f'data-volume="{fx.get("volume", 0.6)}" data-track-index="12"></audio>')
    bgm = assets.get("bgm")
    if bgm:
        audios.append(f'      <audio id="bgm" src="assets/{bgm["path"]}" data-start="0" data-duration="{total}" '
                      f'data-volume="{bgm.get("volume", 0.14)}" data-fade-in="0.5" data-fade-out="1.5" data-track-index="11"></audio>')
    if not args.no_captions and tl.get("captions"):
        hosts.append(f'      <div id="captions" data-composition-id="captions" data-composition-src="compositions/captions.html" '
                     f'data-start="0" data-duration="{total}" data-track-index="5" data-track-kind="captions" '
                     f'data-width="{w}" data-height="{h}" style="z-index: 50"></div>')
        write_generated(proj / "compositions" / "captions.html", captions_comp(tl, w, h, style))

    palette = style.get("palette") or ["#000000", "#ffffff"]
    index = f"""<!doctype html>
{MARK}
<html lang="{esc(script.get('lang', 'vi'))}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={w}, height={h}" />
    <script src="{GSAP}"></script>
    <style>
      {font_faces(assets)}
      :root {{ --ground: {palette[0]}; --ink: {palette[1 % len(palette)]}; }}
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: {w}px; height: {h}px; overflow: hidden; background: var(--ground); }}
      #root {{ position: relative; width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{total}" data-width="{w}" data-height="{h}">
{chr(10).join(hosts)}
{chr(10).join(audios)}
    </div>
    <script>
      const tl = gsap.timeline({{ paused: true }});
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
"""
    if write_generated(proj / "index.html", index):
        print(f"wrote index.html ({len(tl['scenes'])} scenes, {total}s, {w}x{h})")


if __name__ == "__main__":
    main()
